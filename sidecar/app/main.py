    @app.post("/api/conversations/{conversation_id}/attachments")
    async def upload_attachment(state: StateDep, conversation_id: str, file: UploadFile = File(...)) -> dict[str, Any]:
        content = await file.read(5_000_000 + 1)
        if len(content) > 5_000_000:
            raise HTTPException(413, "attachment larger than 5 MB")
        import base64

        return {
            "id": uuid.uuid4().hex,
            "name": file.filename or "attachment",
            "mime_type": file.content_type or "application/octet-stream",
            "data": base64.b64encode(content).decode(),
            "size": len(content),
        }

