    @app.post("/api/conversations/{conversation_id}/messages", response_model=Conversation)
    def send_message(state: StateDep, conversation_id: str, payload: SendMessageInput) -> Conversation:
        row = state.db.get_conversation(conversation_id)
        if row is None:
            raise HTTPException(404, "conversation not found")
        if not payload.content.strip() and not payload.attachments:
            raise HTTPException(400, "message content is required")
        runtime = state.runtime(conversation_id)
        attachments = [a.model_dump(mode="json") for a in payload.attachments]
        runtime.emit(
            "message", role="user", content=payload.content, attachments=attachments or None
        )
        if row["title"] in {"New conversation", ""}:
            state.db.update_conversation(conversation_id, title=_title_from(payload.content))
        state.db.update_conversation(conversation_id, status="running")
        runtime.submit(payload.content, attachments)
        return _conversation(state, state.db.get_conversation(conversation_id) or row)

