DEFAULT_SETTINGS = AppSettings()


# --------------------------------------------------------------- lifecycle


class AppState:
    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self.started_at = time.monotonic()
        self.db = Database(settings.db_path)
        self.db.vault = SecretVault(settings.data_dir)  # type: ignore[attr-defined]
        self.runtimes: dict[str, AgentRuntime] = {}
        self.terminals = SessionRegistry()
        settings_record = self.db.get_setting("settings")
        self.app_settings = AppSettings(**settings_record) if settings_record else DEFAULT_SETTINGS

    # ---------------------------------------------------------- settings
    def save_settings(self, settings: AppSettings) -> AppSettings:
        self.app_settings = settings
        self.db.set_setting("settings", settings.model_dump(mode="json"))
        return settings

    # ---------------------------------------------------------- runtimes
    def runtime(self, conversation_id: str) -> AgentRuntime:
        runtime = self.runtimes.get(conversation_id)
        if runtime is None:
            runtime = AgentRuntime(self.db, conversation_id)
            self.runtimes[conversation_id] = runtime
        return runtime

    def drop_runtime(self, conversation_id: str) -> None:
        runtime = self.runtimes.pop(conversation_id, None)
        if runtime is not None:
            runtime.stop()

    def shutdown(self) -> None:
        for runtime in list(self.runtimes.values()):
            runtime.stop()
        self.terminals.close_all()
        self.db.close()


def create_app(settings: Settings | None = None) -> FastAPI:
    settings = settings or load_settings()

    @asynccontextmanager
    async def lifespan(app: FastAPI) -> AsyncIterator[None]:
        yield
        app.state.ohd.shutdown()

    app = FastAPI(title="OpenHands Desktop Sidecar", version=__version__, lifespan=lifespan)
    app.state.ohd = AppState(settings)
    app.add_middleware(
        CORSMiddleware,
        allow_origins=["http://localhost:5173", "http://127.0.0.1:5173", "app://openhands-desktop"],
        allow_origin_regex=r"^(file://|app://).*$",
        allow_methods=["*"],
        allow_headers=["*"],
    )
    _install_auth(app, settings)
    _install_routes(app)
    return app


def _install_auth(app: FastAPI, settings: Settings) -> None:
    token = settings.session_token

    @app.middleware("http")
    async def require_token(request: Request, call_next):  # type: ignore[no-untyped-def]
        if token and request.url.path not in {"/health", "/api/health"}:
            header = request.headers.get("authorization", "")
            supplied = header.removeprefix("Bearer ").strip() if header.startswith("Bearer ") else ""
            if not supplied or not _compare(supplied, token):
                return JSONResponse({"detail": "invalid or missing session token"}, status_code=401)
        return await call_next(request)


def _compare(a: str, b: str) -> bool:
    import hmac

    return hmac.compare_digest(a, b)


def _state(request: Request) -> AppState:
    return request.app.state.ohd


