        target.parent.mkdir(parents=True, exist_ok=True)
        result = run_command(f'git clone "{url}" "{target}"', cwd=target.parent)
        if not result.ok:
            raise HTTPException(400, f"git clone failed: {result.output}")
        row = state.db.upsert_workspace(
            {"path": str(target), "kind": "local", "name": target.name, "git_remote": url}
        )
        return Workspace(**public_workspace(row, state.settings.sandbox_image))

