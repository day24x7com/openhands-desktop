def _conversation(state: AppState, row: dict[str, Any]) -> Conversation:
    runtime = state.runtimes.get(row["id"])
    pending = row.get("pending_approval")
    if pending and not pending.get("conversation_id"):
        pending = {**pending, "conversation_id": row["id"]}
    return Conversation(
        id=row["id"],
        title=row["title"],
        workspace_id=row["workspace_id"],
        mode=row["mode"],
        llm_profile_id=row.get("llm_profile_id"),
        status=row["status"],
        pinned=bool(row.get("pinned")),
        created_at=row["created_at"],
        updated_at=row["updated_at"],
        cost_total=float(row.get("cost_total") or 0),
        tokens_total=int(row.get("tokens_total") or 0),
        pending_approval=pending,
        queued_messages=runtime.queued_count() if runtime else 0,
    )


def _control(state: AppState, conversation_id: str, action: str) -> Conversation:
    row = state.db.get_conversation(conversation_id)
    if row is None:
        raise HTTPException(404, "conversation not found")
    runtime = state.runtime(conversation_id)
    if action == "run":
        runtime.start()
    elif action == "pause":
        runtime.pause()
    elif action == "resume":
        runtime.resume()
    elif action == "stop":
        runtime.stop()
        state.db.update_conversation(conversation_id, status="idle")
    return _conversation(state, state.db.get_conversation(conversation_id) or row)


def _workspace_for_conversation(state: AppState, conversation_id: str):
    row = state.db.get_conversation(conversation_id)
    if row is None:
        raise HTTPException(404, "conversation not found")
    workspace_row = state.db.get_workspace(row["workspace_id"])
    if workspace_row is None:
        raise HTTPException(404, "workspace not found")
    return workspace_from_row(workspace_row, row.get("mode") or "local", state.settings.sandbox_image)


def _title_from(content: str) -> str:
    line = content.strip().splitlines()[0] if content.strip() else "New conversation"
    return (line[:60] + "…") if len(line) > 60 else line


def _slug(value: str) -> str:
    slug = "".join(c if c.isalnum() or c in "-_" else "-" for c in value.lower()).strip("-")
    return slug[:60] or "conversation"


def _repo_name(url: str) -> str:
    cleaned = url.rstrip("/").split("/")[-1]
    return cleaned[:-4] if cleaned.endswith(".git") else cleaned


def _render_markdown(conversation: dict[str, Any], events: list[dict[str, Any]]) -> str:
    lines = [f"# {conversation['title']}", "", f"- Created: {conversation['created_at']}", ""]
    for event in events:
        kind = event["type"]
        if kind == "message":
            who = "**You**" if event.get("role") == "user" else "**OpenHands**"
            lines += [f"### {who}", "", event.get("content") or "", ""]
        elif kind == "thinking":
            lines += ["> _thinking:_ " + (event.get("content") or "").replace("\n", " "), ""]
        elif kind == "action":
            lines += [f"**Action** `{event.get('tool')}`: {event.get('summary')}", ""]
        elif kind == "observation":
            status = "ok" if event.get("ok") else "failed"
            lines += [f"**Observation** ({status}):", "", "```", (event.get("content") or "")[:4000], "```", ""]
    return "\n".join(lines)


