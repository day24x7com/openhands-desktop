    @app.post("/api/conversations/{conversation_id}/approval", response_model=Conversation)
    def approve(state: StateDep, conversation_id: str, payload: dict[str, Any] = Body(...)) -> Conversation:
        approval_id = payload.get("approval_id")
        approved = bool(payload.get("approved"))
        remember = bool(payload.get("remember", False))
        if not approval_id:
            raise HTTPException(400, "approval_id is required")
        if conversation_id not in state.runtimes:
            raise HTTPException(404, "conversation runtime not active")
        state.runtime(conversation_id).resolve_approval(str(approval_id), approved, remember)
        row = state.db.get_conversation(conversation_id)
        if row is None:
            raise HTTPException(404, "conversation not found")
        return _conversation(state, row)

    @app.get("/api/conversations/{conversation_id}/export")
    def export_conversation(
        state: StateDep, conversation_id: str, format: str = Query(default="markdown", pattern="^(markdown|json)$")
    ) -> Response:
        row = state.db.get_conversation(conversation_id)
        if row is None:
            raise HTTPException(404, "conversation not found")
        events = state.db.list_events(conversation_id)
        if format == "json":
            body = json.dumps({"conversation": row, "events": events}, indent=2, default=str)
            media = "application/json"
            filename = f"{_slug(row['title'])}.json"
        else:
            body = _render_markdown(row, events)
            media = "text/markdown; charset=utf-8"
            filename = f"{_slug(row['title'])}.md"
        return Response(
            content=body,
            media_type=media,
            headers={"Content-Disposition": f'attachment; filename="{filename}"'},
        )

